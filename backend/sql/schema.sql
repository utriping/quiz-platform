CREATE TABLE IF NOT EXISTS users (
 id SERIAL PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(255) UNIQUE NOT NULL,
 password_hash TEXT NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'STUDENT' CHECK(role IN ('ADMIN','STUDENT')),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS categories (
 id SERIAL PRIMARY KEY, name VARCHAR(100) UNIQUE NOT NULL, description TEXT DEFAULT '', created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS quizzes (
 id SERIAL PRIMARY KEY, title VARCHAR(180) NOT NULL, description TEXT DEFAULT '', category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
 difficulty VARCHAR(20) NOT NULL DEFAULT 'Beginner' CHECK(difficulty IN ('Beginner','Intermediate','Advanced')),
 duration_minutes INTEGER NOT NULL CHECK(duration_minutes > 0), passing_score NUMERIC(5,2) NOT NULL DEFAULT 60 CHECK(passing_score BETWEEN 0 AND 100),
 max_attempts INTEGER NOT NULL DEFAULT 0 CHECK(max_attempts >= 0), status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PUBLISHED','UNPUBLISHED')),
 created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS questions (
 id SERIAL PRIMARY KEY, quiz_id INTEGER NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
 question_text TEXT NOT NULL, marks NUMERIC(7,2) NOT NULL DEFAULT 1 CHECK(marks > 0), explanation TEXT DEFAULT '',
 difficulty VARCHAR(20) NOT NULL DEFAULT 'Beginner', position INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS options (
 id SERIAL PRIMARY KEY, question_id INTEGER NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
 option_text TEXT NOT NULL, is_correct BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS attempts (
 id SERIAL PRIMARY KEY, quiz_id INTEGER NOT NULL REFERENCES quizzes(id), user_id INTEGER NOT NULL REFERENCES users(id),
 score NUMERIC(9,2) NOT NULL DEFAULT 0, total_marks NUMERIC(9,2) NOT NULL DEFAULT 0, percentage NUMERIC(5,2) NOT NULL DEFAULT 0,
 correct_answers INTEGER NOT NULL DEFAULT 0, incorrect_answers INTEGER NOT NULL DEFAULT 0, unanswered INTEGER NOT NULL DEFAULT 0,
 time_taken INTEGER NOT NULL DEFAULT 0, status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK(status IN ('IN_PROGRESS','PASSED','FAILED')),
 started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), expires_at TIMESTAMPTZ NOT NULL, completed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS answers (
 id SERIAL PRIMARY KEY, attempt_id INTEGER NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
 question_id INTEGER NOT NULL REFERENCES questions(id), selected_option_id INTEGER REFERENCES options(id), is_correct BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(attempt_id, question_id)
);
CREATE INDEX IF NOT EXISTS idx_attempts_user ON attempts(user_id);
CREATE INDEX IF NOT EXISTS idx_attempts_quiz ON attempts(quiz_id);
CREATE INDEX IF NOT EXISTS idx_quizzes_status ON quizzes(status);
